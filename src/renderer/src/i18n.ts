export function translate(lang: Language, key: Key, vars?: Record<string, string | number>): string {
  let s = dict[lang]?.[key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function stageKey(stage: Stage): Key | null {
  const map: Partial<Record<Stage, Key>> = {
    manifest: 'stage.manifest',
    java: 'stage.java',
    minecraft: 'stage.minecraft',
    loader: 'stage.loader',
    assets: 'stage.assets',
    mods: 'stage.mods',
    packs: 'stage.packs',
    launching: 'stage.launching',
    running: 'stage.running',
    error: 'stage.error'
  }
  return map[stage] ?? null
}
